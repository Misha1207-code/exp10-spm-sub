#!/usr/bin/env python3
"""FinOps cost observability demo using synthetic CSV billing data."""
import csv, html
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "sample_billing.csv"
OUT_CSV = ROOT / "demo" / "finops_summary.csv"
OUT_HTML = ROOT / "demo" / "finops_dashboard.html"

def main():
    with SOURCE.open(newline="", encoding="utf-8") as f:
        records = list(csv.DictReader(f))
    by_service = defaultdict(float)
    total = 0.0
    budget = 0.0
    idle = []
    overspend = []
    for r in records:
        cost = float(r["cost_usd"]); b = float(r["budget_usd"])
        total += cost; budget += b
        by_service[r["service"]] += cost
        if r["idle"].strip().lower() == "yes":
            idle.append(r)
        if cost > b:
            overspend.append(r)
    variance = total - budget
    print("=== FinOps Cost Observability Demo (synthetic data) ===")
    print(f"Resources analyzed: {len(records)}")
    print(f"Total cost: ${total:.2f}")
    print(f"Total budget: ${budget:.2f}")
    print(f"Budget variance: ${variance:+.2f} ({variance/budget*100:+.1f}%)")
    print("\nCost by service:")
    for service, cost in sorted(by_service.items(), key=lambda x: x[1], reverse=True):
        print(f"  {service:12s} ${cost:8.2f}")
    print("\nBudget alerts:")
    for r in overspend:
        print(f"  ALERT {r['resource']}: ${float(r['cost_usd']):.2f} > budget ${float(r['budget_usd']):.2f}")
    print("\nIdle-resource candidates (review before action):")
    for r in idle:
        print(f"  REVIEW {r['resource']}: utilization {r['utilization_pct']}%, cost ${float(r['cost_usd']):.2f}")
    with OUT_CSV.open("w", newline="", encoding="utf-8") as f:
        w=csv.writer(f); w.writerow(["service","cost_usd"])
        for s,c in sorted(by_service.items()): w.writerow([s, f"{c:.2f}"])
    bars=[]
    max_cost=max(by_service.values()) if by_service else 1
    for service,cost in sorted(by_service.items(), key=lambda x:x[1], reverse=True):
        width=max(2, int(cost/max_cost*100))
        bars.append(f"<div class='barrow'><span>{html.escape(service)}</span><div class='track'><div class='bar' style='width:{width}%'></div></div><b>${cost:.2f}</b></div>")
    alert_html="".join(f"<li><b>{html.escape(r['resource'])}</b>: ${float(r['cost_usd']):.2f} cost vs ${float(r['budget_usd']):.2f} budget</li>" for r in overspend) or "<li>No overspend detected.</li>"
    idle_html="".join(f"<li><b>{html.escape(r['resource'])}</b> — {r['utilization_pct']}% utilization; ${float(r['cost_usd']):.2f} cost</li>" for r in idle) or "<li>No idle candidates.</li>"
    page=f"""<!doctype html><html><head><meta charset="utf-8"><title>FinOps Cost Observability</title>
<style>body{{font-family:Arial,sans-serif;background:#f3f6fb;color:#19283c;margin:0;padding:30px}}h1{{margin-bottom:4px}}.sub{{color:#596b82}}.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(190px,1fr));gap:14px;margin:24px 0}}.card{{background:white;padding:20px;border-radius:12px;box-shadow:0 2px 9px #dce3ed}}.num{{font-size:27px;font-weight:bold;margin-top:8px}}.section{{background:white;padding:22px;border-radius:12px;margin:16px 0}}.barrow{{display:grid;grid-template-columns:100px 1fr 90px;gap:12px;align-items:center;margin:13px 0}}.track{{height:17px;background:#e6ecf4;border-radius:8px;overflow:hidden}}.bar{{height:100%;background:#287b8e;border-radius:8px}}.warn{{color:#9a4c00}}footer{{color:#64748b;font-size:12px;margin-top:25px}}</style></head><body>
<h1>FinOps Cost Observability</h1><div class="sub">Experiment X • Sample billing data • Generated by Python</div>
<div class="grid"><div class="card">Total cost<div class="num">${total:.2f}</div></div><div class="card">Budget<div class="num">${budget:.2f}</div></div><div class="card">Budget variance<div class="num {'warn' if variance>0 else ''}">${variance:+.2f}</div></div><div class="card">Idle candidates<div class="num">{len(idle)}</div></div></div>
<div class="section"><h2>Spend by service</h2>{''.join(bars)}</div>
<div class="section"><h2 class="warn">Budget alerts</h2><ul>{alert_html}</ul></div>
<div class="section"><h2>Idle-resource candidates</h2><p>These are candidates for human review, not automatic deletion recommendations.</p><ul>{idle_html}</ul></div>
<footer>Data is synthetic for demonstration. Costs are illustrative, not live cloud prices. Validate ownership and workload requirements before changing resources.</footer></body></html>"""
    OUT_HTML.write_text(page,encoding="utf-8")
    print(f"\nWrote: {OUT_CSV.relative_to(ROOT)}")
    print(f"Wrote: {OUT_HTML.relative_to(ROOT)}")
    print("PASS: cost aggregation, budget checks, and dashboard generation completed.")
if __name__=="__main__": main()
